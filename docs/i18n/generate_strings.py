"""Generates Android string resources and the message lookup from docs/i18n/catalog.py.

    python docs/i18n/generate_strings.py

Writes app/src/main/res/values{,-zu,-tn}/strings.xml and
app/src/main/java/com/example/nexus/ui/components/LocalizedMessages.kt.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from catalog import PLURALS, STRINGS  # noqa: E402

RES = os.path.join(ROOT, "app", "src", "main", "res")
LOCALES = [("values", 1), ("values-zu", 2), ("values-tn", 3)]


def esc(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')


def check() -> None:
    keys = [s[0] for s in STRINGS] + [p[0] for p in PLURALS]
    dupes = {k for k in keys if keys.count(k) > 1}
    if dupes:
        raise SystemExit(f"duplicate keys: {sorted(dupes)}")
    english = [s[1] for s in STRINGS if s[4] == "msg"]
    if len(english) != len(set(english)):
        raise SystemExit("two 'msg' entries share the same English text")
    for key, *texts, kind in STRINGS:
        args = [sorted(set(__import__("re").findall(r"%\d\$[sd]", t))) for t in texts]
        if any(a != args[0] for a in args):
            raise SystemExit(f"{key}: placeholders differ between languages: {args}")


def write_resources() -> None:
    for folder, index in LOCALES:
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by docs/i18n/generate_strings.py from docs/i18n/catalog.py. Do not edit by hand. -->",
                 "<resources>"]
        for entry in STRINGS:
            key, text = entry[0], entry[index]
            if folder != "values" and key == "app_name":
                continue
            lines.append(f'    <string name="{key}">{esc(text)}</string>')
        for key, *forms in PLURALS:
            one, other = forms[index - 1]
            lines += [f'    <plurals name="{key}">',
                      f'        <item quantity="one">{esc(one)}</item>',
                      f'        <item quantity="other">{esc(other)}</item>',
                      "    </plurals>"]
        lines.append("</resources>")
        os.makedirs(os.path.join(RES, folder), exist_ok=True)
        with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")


def write_lookup() -> None:
    rows = "\n".join(
        f'        "{e[1].replace(chr(34), chr(92) + chr(34))}" to R.string.{e[0]},'
        for e in STRINGS if e[4] == "msg")
    kotlin = f'''package com.example.nexus.ui.components

// Generated by docs/i18n/generate_strings.py from docs/i18n/catalog.py. Do not edit by hand.

import androidx.compose.runtime.Composable
import androidx.compose.ui.res.stringResource
import com.example.nexus.R

/**
 * ViewModels and SyncManager produce English messages so they stay free of Android resources and
 * unit-testable. This table translates them into the selected language (en/zu/tn) at render time.
 * Unknown text (e.g. a server message) is shown unchanged.
 */
private val messageKeys: Map<String, Int> =
    mapOf(
{rows}
    )

@Composable
fun localizedMessage(message: String): String = messageKeys[message]?.let {{ stringResource(it) }} ?: message
'''
    path = os.path.join(ROOT, "app", "src", "main", "java", "com", "example", "nexus", "ui", "components", "LocalizedMessages.kt")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(kotlin)


if __name__ == "__main__":
    check()
    write_resources()
    write_lookup()
    print(f"{len(STRINGS)} strings and {len(PLURALS)} plurals written for en, zu, tn")
